const f = (n: number) => String(Math.round(n * 1000) / 1000);
/** `calc(<pct>% +/- <px>px)` */
const lin = (pct: number, px: number) =>
  `calc(${f(pct)}% ${px < 0 ? "-" : "+"} ${f(Math.abs(px))}px)`;

/**
 * Chromium rejects calc() that mixes % and px inside a radial-gradient SIZE (but accepts it in `at` and in
 * background-size), so the ellipse is sized through the background tile instead:
 *   tile  = 2*(rx*W + d) x 2*(ry*H + d)   [W,H = original box; W' = W + 2m is the grown box]  -> background-size
 *   tile is centred in the grown box (background-position 50% 50%); the gradient (radii = 50% of the tile)
 *   is moved to the original centre with `at calc(P% + Qpx)`.
 */
function axis(r: number, c: number, m: number, d: number) {
  const a = 2 * r;
  const b = 2 * d - 2 * a * m; // tile size = a*W' + b
  const P = ((c - 0.5) / a + 0.5) * 100;
  const Q = (1 - 2 * c) * m - ((c - 0.5) * b) / a;
  return { size: lin(a * 100, b), at: lin(P, Q) };
}

function gradient(s: HazeSpec, t: Table): { image: string; size: string } {
  const x = axis(s.rx, s.cx, s.m, t.d);
  const y = axis(s.ry, s.cy, s.m, t.d);
  const n = t.stops.length;
  const st = t.stops.map(([r, g, b, a], i) => `rgba(${r}, ${g}, ${b}, ${a}) ${f((i / n) * 100)}%`);
  return {
    image: `radial-gradient(ellipse 50% 50% at ${x.at} ${y.at}, ${st.join(", ")}, transparent 100%)`,
    size: `${x.size} ${y.size}`,
  };
}

