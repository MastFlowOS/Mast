/**
 * Pre-softened replacement for the blurred atmosphere haze layers.
 *
 * GENERATED from a numerical model of the previous implementation
 * (radial-gradient element + CSS `filter: blur(110-150px)` + opacity, clipped by its parent).
 * Each layer is now ONE element painting ONE elliptical radial-gradient - no runtime filter.
 *
 *  - `m`   : px the element's box is grown on every side (margin:-m; padding:m; content-box, see `.atmo-soft`
 *            in styles.css) so the area the blur used to spill into is still painted.
 *  - `rx/ry/cx/cy`: the original gradient's radii / centre as a fraction of the ORIGINAL box.
 *  - `wide`/`narrow`: stop tables (premultiplied-RGBA samples of the blurred field on a normalised radius) plus
 *            `d`, the px the gradient radius is widened by (stands in for the blur). Blur spreads a small box's
 *            energy over a fixed pixel radius, so the amplitude depends on box size; one table cannot serve both
 *            desktop and phones, hence two (switched by a media query in styles.css, <= 700px = narrow).
 *  - stops are UNIT-opacity colours: the element's existing opacity class / atmo-haze-pulse animation still
 *            multiplies them exactly as before.
 */
